def long_string(text, level):
    eq = "=" * level
    # A newline right after [==[ is dropped by Lua, so the source is kept exact.
    return f"[{eq}[\n{text}]{eq}]"


def bracket_level(texts):
    level = 1
    while any(f"]{'=' * level}]" in t for t in texts):
        level += 1
    return level


def installs(scripts, level):
    out = []
    for var, cls, parent, name, rel in scripts:
        prefix = f"local {var} = " if var else ""
        source = (SRC / rel).read_text()
        out.append(f"\n-- {rel}\n{prefix}install(\"{cls}\", {parent}, \"{name}\", {long_string(source, level)})\n")
    return "".join(out)


def write(name, text):
    path = DIST / name
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    print(f"wrote {path.relative_to(ROOT)} ({path.stat().st_size // 1024} KB)")


def build():
    all_sources = [(SRC / rel).read_text() for *_, rel in ANIMATOR + WORLD]
    level = bracket_level(all_sources)

    write("ChadWorld_Installer.lua", WORLD_HEADER + PRELUDE + installs(ANIMATOR + WORLD, level) + WORLD_FOOTER)

    dummy = (SRC / "baseplate" / "Dummy.luau").read_text()
    dummy_block = f"\n-- baseplate/Dummy.luau\nlocal buildDummy = (function()\n{dummy}\nend)()\n"
    write("ChadBaseplate_Installer.lua",
          BASEPLATE_HEADER + PRELUDE + installs(ANIMATOR, level) + dummy_block + BASEPLATE_FOOTER)


if __name__ == "__main__":
    build()
